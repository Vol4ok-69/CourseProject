namespace Application.Analyzers;

/// <summary>
/// Типизированный статус выполнения анализатора базы данных в соответствии с ADR-001 / TD-002.
/// </summary>
public enum DatabaseAnalysisExecutionStatus
{
    /// <summary>
    /// Анализ ещё не запускался или сброшен перед новым запуском.
    /// </summary>
    NotStarted,

    /// <summary>
    /// Анализ успешно выполнен в изолированном контейнере, сформированы результаты.
    /// </summary>
    Success,

    /// <summary>
    /// Анализ частично выполнен (например, часть сущностей содержала синтаксические предупреждения или пропущена, но анализ завершился).
    /// </summary>
    PartialSuccess,

    /// <summary>
    /// Анализ безопасно пропущен по информационным причинам (например, в проекте отсутствует DbContext).
    /// </summary>
    InformationSkipped,

    /// <summary>
    /// Ошибка запуска или выполнения изолированного контейнера.
    /// </summary>
    ContainerError,

    /// <summary>
    /// Превышен лимит времени (таймаут) выполнения в изолированном контейнере.
    /// </summary>
    ContainerTimeout,

    /// <summary>
    /// Ошибка статического извлечения метаданных Roslyn (например, недоступен репозиторий или критический сбой Roslyn).
    /// </summary>
    ExtractionError,

    /// <summary>
    /// Внутренняя непредвиденная ошибка анализатора базы данных.
    /// </summary>
    InternalError
}
